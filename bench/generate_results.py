"""Generate RESULTS.md and badge-latency.json from the newest latency results.

RESULTS.md is the linkable summary table of the latest latency run: provider,
p50, p95, success rate, sample size, run date. badge-latency.json is a
shields.io endpoint payload showing ParlayAPI's own p50, so the README (and
nothing else) can render a live badge. Both are regenerated by every run;
do not hand-edit either file.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import ROOT

ORDER = ["parlayapi", "the_odds_api", "oddspapi", "sharpapi", "sportsgameodds", "therundown"]


def latest_date():
    dates = sorted(p.name for p in (ROOT / "results").iterdir() if p.is_dir())
    return dates[-1]


def ms(seconds):
    return f"{seconds * 1000:.0f} ms" if seconds is not None else "n/a"


def p95_of(entry):
    """p95 for entries written before the field existed: fall back to samples."""
    if entry.get("p95_s") is not None:
        return entry["p95_s"]
    samples = sorted(entry.get("samples_s") or [])
    if not samples:
        return None
    return samples[max(0, int(len(samples) * 0.95) - 1)]


def main(date=None):
    date = date or latest_date()
    with open(ROOT / "results" / date / "latency.json") as f:
        lat = json.load(f)

    L = []
    A = L.append
    A("# Latest latency results")
    A("")
    A("> **Disclosure:** this repo is maintained by ParlayAPI's founder. Every number "
      "below is produced by [`bench/probe_latency.py`](bench/probe_latency.py), which "
      "you can rerun yourself with no API keys. See [METHODOLOGY.md](METHODOLOGY.md) "
      "and the caveats before quoting anything.")
    A("")
    A(f"Run date: **{date}** (UTC, {lat['run_at_utc']}). "
      f"Vantage point: `{lat['vantage_point']['platform']}` (a GitHub-hosted runner for "
      "scheduled runs). Raw samples: "
      f"[`results/{date}/latency.json`](results/{date}/latency.json).")
    A("")
    A("**Caveats, do not skip:** " + lat["caveats"] + " Rows whose status is 401 are "
      "not comparable to rows serving real data with a 200.")
    A("")
    A("| Provider | What was measured | Statuses seen | p50 | p95 | Success rate | Sample size | Run date |")
    A("|---|---|---|---|---|---|---|---|")
    for vid in ORDER:
        e = lat["vendors"][vid]
        attempted = e.get("n_attempted", e["n_ok"] + e["errors"])
        success = f"{e['n_ok']}/{attempted}"
        A(f"| {e['name']} | {e['target']} | {e['response_statuses_seen']} "
          f"| {ms(e['median_s'])} | {ms(p95_of(e))} | {success} | {attempted} | {date} |")
    A("")
    A("A row's p50/p95 are the median and 95th percentile of total round-trip time "
      "over the sample; success rate is completed HTTP exchanges (any status) over "
      "attempts. History of all runs lives in [`results/`](results/).")
    A("")

    results_md = "\n".join(L)
    for bad in ("\u2014", "\u2013"):
        assert bad not in results_md, "em/en dash found in generated RESULTS.md"
    (ROOT / "RESULTS.md").write_text(results_md)
    print(f"wrote {ROOT / 'RESULTS.md'} from results/{date}")

    # shields.io endpoint badge: ParlayAPI's own p50 from this run. Factual,
    # no comparative wording; the tables carry the comparison and its caveats.
    p = lat["vendors"]["parlayapi"]
    badge = {
        "schemaVersion": 1,
        "label": "ParlayAPI p50",
        "message": ms(p["median_s"]) if p["median_s"] is not None else "no data",
        "color": "blue" if p["median_s"] is not None else "lightgrey",
        "cacheSeconds": 3600,
    }
    with open(ROOT / "badge-latency.json", "w") as f:
        json.dump(badge, f, indent=2)
        f.write("\n")
    print(f"wrote {ROOT / 'badge-latency.json'}: {badge['label']} = {badge['message']}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else None)
